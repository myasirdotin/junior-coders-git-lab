#!/usr/bin/env node
// Builds the search index for the Cheat Sheets page (library/cheatsheets/index.html).
//
// For every cheatsheet-*.html in the site root it:
//   1. gives each <div class="cheat-card"> a stable id ("card-<title>") so a search result can jump to it
//      (only added when missing, so running this twice changes nothing);
//   2. reads every table row (code | meaning) and writes them to js/data/cheat-index.js as
//      window.JC_CHEAT_INDEX = { sheets: {...}, rows: [[sheet, cardId, cardTitle, code, meaning], ...] }.
//
// Run after adding or editing a cheat sheet:  node scripts/build-cheat-index.js
const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..');
const OUT = path.join(ROOT, 'js', 'data', 'cheat-index.js');

const ENTITIES = { amp: '&', lt: '<', gt: '>', quot: '"', '#39': "'", apos: "'", nbsp: ' ', mdash: '—', ndash: '–', rarr: '→' };
const decode = (s) => s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (m, e) => {
  if (e[0] === '#') return String.fromCodePoint(e[1].toLowerCase() === 'x' ? parseInt(e.slice(2), 16) : parseInt(e.slice(1), 10));
  return ENTITIES[e.toLowerCase()] !== undefined ? ENTITIES[e.toLowerCase()] : m;
});
const text = (html) => decode(html.replace(/<[^>]+>/g, '')).replace(/\s+/g, ' ').trim();
const slug = (s) => s.toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')       // emoji, punctuation, spaces, non-ASCII → dashes
  .replace(/^\d+-/, '')               // "3. Creation" → "creation"
  .slice(0, 40)
  .replace(/^-+|-+$/g, '') || 'card';

const files = fs.readdirSync(ROOT).filter((f) => /^cheatsheet-[a-z]+\.html$/.test(f)).sort();
const sheets = {};
const rows = [];

for (const file of files) {
  const key = file.replace(/^cheatsheet-|\.html$/g, '');
  const full = path.join(ROOT, file);
  let html = fs.readFileSync(full, 'utf8');
  const titleMatch = html.match(/<h1[^>]*>([\s\S]*?)<\/h1>/);
  const used = new Set();
  let cardCount = 0;

  // Walk the cards in order; each card is "<div class="cheat-card" ...> header ... </table>"
  html = html.replace(/<div class="cheat-card"([^>]*)>([\s\S]*?<\/table>)/g, (whole, attrs, inner) => {
    const header = inner.match(/class="cheat-card-header[^"]*"[^>]*>([\s\S]*?)<\/div>/);
    const title = header ? text(header[1]).replace(/^[^\p{L}\p{N}]+/u, '') : 'Card';
    let id = (attrs.match(/\sid="([^"]+)"/) || [])[1];
    if (!id) {
      id = 'card-' + slug(title);
      let n = 2;
      while (used.has(id)) id = 'card-' + slug(title) + '-' + n++;
      attrs = ` id="${id}"` + attrs;
    }
    used.add(id);
    cardCount++;
    for (const tr of inner.match(/<tr>[\s\S]*?<\/tr>/g) || []) {
      const cells = tr.match(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/g) || [];
      if (cells.length < 2) continue;
      const code = text(cells[0]);
      const meaning = text(cells.slice(1).join(' '));
      if (code || meaning) rows.push([key, id, title, code, meaning]);
    }
    return `<div class="cheat-card"${attrs}>${inner}`;
  });

  if (html !== fs.readFileSync(full, "utf8")) fs.writeFileSync(full, html);   // only touch a sheet when an id was added
  sheets[key] = { file, title: titleMatch ? text(titleMatch[1]) : key, cards: cardCount,
                  rows: rows.filter((r) => r[0] === key).length };
}

const banner = '// Generated by scripts/build-cheat-index.js. Do not edit by hand: edit a cheatsheet-*.html and re-run the script.\n';
fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, banner + 'window.JC_CHEAT_INDEX = ' + JSON.stringify({ sheets, rows }) + ';\n');
console.log(`Indexed ${rows.length} rows from ${files.length} cheat sheets → ${path.relative(ROOT, OUT)}`);
for (const [k, v] of Object.entries(sheets)) console.log(`  ${k.padEnd(14)} ${String(v.cards).padStart(2)} cards ${String(v.rows).padStart(3)} rows`);

// Readable layout (class "cheat-v2", GEMINI §7l): every box needs a short explanation (.cheat-intro) and a
// "Learn more" line (.cheat-more) whose chapter links exist in that textbook. Problems are listed as warnings.
const warnings = [];
const chapterExists = (book, n) => {
  const dir = path.join(ROOT, book);
  if (!fs.existsSync(dir)) return false;
  const want = new RegExp('^ch0*' + n + '-.*\.md$');
  const walk = (d) => fs.readdirSync(d, { withFileTypes: true }).some((e) =>
    e.isDirectory() ? walk(path.join(d, e.name)) : want.test(e.name));
  return walk(dir);
};
for (const file of files) {
  const html = fs.readFileSync(path.join(ROOT, file), 'utf8');
  if (!/class="cheatsheet-container cheat-v2"/.test(html)) { warnings.push(`${file}: not on the readable layout (cheat-v2)`); continue; }
  const cards = html.split('<div class="cheat-card"').slice(1);
  cards.forEach((c) => {
    const id = (c.match(/id="([^"]+)"/) || [])[1] || '?';
    if (!/class="cheat-intro"/.test(c)) warnings.push(`${file} #${id}: no explanation (cheat-intro)`);
    if (!/class="cheat-more"/.test(c)) warnings.push(`${file} #${id}: no Learn more line (cheat-more)`);
    for (const m of c.matchAll(/href="(book-[a-z]+)\/index\.html#ch(\d+)"/g)) {
      if (!chapterExists(m[1], m[2])) warnings.push(`${file} #${id}: ${m[1]} has no chapter ${m[2]}`);
    }
  });
}
if (warnings.length) console.log(`\nWARNINGS (${warnings.length}):\n  ` + warnings.join('\n  '));
else console.log('\nAll boxes have an explanation and working chapter links.');
